#!/usr/bin/env node

import { createRequire } from "node:module";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const require = createRequire(import.meta.url);

const ICONS = [
  "information-circle",
  "pencil",
  "check-circle",
  "exclamation-triangle",
  "exclamation-circle",
  "megaphone",
];

const rootDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
if (args.length && (args.length !== 2 || args[0] !== "--output-dir")) {
  throw new Error("Usage: generate-heroicons.mjs [--output-dir DIRECTORY]");
}
const outputPath = join(
  args.length ? resolve(args[1]) : join(rootDir, "generated"),
  "generatedHeroicons.ts",
);

function resolveHeroiconsDir() {
  const candidatePaths = [
    rootDir,
    process.cwd(),
    resolve(rootDir, "..", "..", "examples", "expo-preview"),
  ];

  for (const candidatePath of candidatePaths) {
    try {
      const packageJsonPath = require.resolve("heroicons/package.json", {
        paths: [candidatePath],
      });
      return dirname(packageJsonPath);
    } catch {
      // Try the next lookup root.
    }
  }

  throw new Error(
    "Unable to resolve the heroicons package. Run npm install before generating icons.",
  );
}

function getAttribute(source, name) {
  const pattern = new RegExp(`${name}="([^"]*)"`);
  const match = source.match(pattern);
  return match ? decodeXml(match[1]) : undefined;
}

function decodeXml(value) {
  return value
    .replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'")
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">");
}

function parseSvg(svg, iconName) {
  const viewBox = getAttribute(svg, "viewBox");
  if (!viewBox) {
    throw new Error(`Missing viewBox in ${iconName}.svg`);
  }

  const paths = Array.from(svg.matchAll(/<path\b([^>]*)\/?>/g)).map(
    (match) => {
      const attributes = match[1];
      const d = getAttribute(attributes, "d");
      if (!d) {
        throw new Error(`Missing path d in ${iconName}.svg`);
      }

      return {
        d,
        fillRule: getAttribute(attributes, "fill-rule"),
        clipRule: getAttribute(attributes, "clip-rule"),
      };
    },
  );

  if (paths.length === 0) {
    throw new Error(`Missing path elements in ${iconName}.svg`);
  }

  return { viewBox, paths };
}

function toTsString(value) {
  return JSON.stringify(value);
}

function generate() {
  const heroiconsDir = resolveHeroiconsDir();
  const heroiconsPackageJson = JSON.parse(
    readFileSync(join(heroiconsDir, "package.json"), "utf8"),
  );
  const sourceDir = join(heroiconsDir, "24", "solid");
  const definitions = ICONS.map((iconName) => {
    const svgPath = join(sourceDir, `${iconName}.svg`);
    const svg = readFileSync(svgPath, "utf8");
    return [iconName, parseSvg(svg, iconName)];
  });

  const iconUnion = ICONS.map((iconName) => `  | ${toTsString(iconName)}`).join(
    "\n",
  );
  const entries = definitions
    .map(([iconName, definition]) => {
      const paths = definition.paths
        .map((pathDefinition) => {
          const attributes = [
            `d: ${toTsString(pathDefinition.d)}`,
            pathDefinition.fillRule
              ? `fillRule: ${toTsString(pathDefinition.fillRule)}`
              : undefined,
            pathDefinition.clipRule
              ? `clipRule: ${toTsString(pathDefinition.clipRule)}`
              : undefined,
          ]
            .filter(Boolean)
            .join(", ");
          return `      { ${attributes} },`;
        })
        .join("\n");

      return `  ${toTsString(iconName)}: {\n    viewBox: ${toTsString(
        definition.viewBox,
      )},\n    paths: [\n${paths}\n    ],\n  },`;
    })
    .join("\n");

  const output = `// This file is generated by scripts/generate-heroicons.mjs.\n// Source: heroicons@${heroiconsPackageJson.version} 24/solid/*.svg.\n// Do not edit manually.\n\nexport type HeroiconSolidName =\n${iconUnion};\n\nexport type HeroiconPathDefinition = {\n  d: string;\n  fillRule?: \"evenodd\" | \"nonzero\";\n  clipRule?: \"evenodd\" | \"nonzero\";\n};\n\nexport type HeroiconDefinition = {\n  viewBox: string;\n  paths: readonly HeroiconPathDefinition[];\n};\n\nexport const HEROICON_SOLID_DEFINITIONS: Record<\n  HeroiconSolidName,\n  HeroiconDefinition\n> = {\n${entries}\n};\n`;

  mkdirSync(dirname(outputPath), { recursive: true });
  writeFileSync(outputPath, output);
  console.error(
    `Generated ${relative(process.cwd(), outputPath)} from ${relative(
      process.cwd(),
      sourceDir,
    )}`,
  );
}

generate();

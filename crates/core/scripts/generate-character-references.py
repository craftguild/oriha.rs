#!/usr/bin/env python3
"""Generate the CommonMark named-reference vocabulary from the pinned WHATWG JSON."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "entity-data/whatwg-entities.json"
OUTPUT = ROOT / "src/character_reference/names.rs"


def generated():
    raw = SOURCE.read_bytes()
    entries = json.loads(raw)
    names = []
    for key, entry in entries.items():
        if not key.endswith(";"):
            continue
        name = key[1:-1]
        assert key.startswith("&") and name.isascii() and name.isalnum()
        assert [ord(c) for c in entry["characters"]] == entry["codepoints"]
        assert 1 <= len(entry["characters"]) <= 2
        value = "".join("\\u{%x}" % ord(c) for c in entry["characters"])
        names.append((name, value))
    names.sort()
    assert len(names) == len({name for name, _ in names})
    lines = [
        "// Generated by scripts/generate-character-references.py; do not edit.",
        "// Source: https://html.spec.whatwg.org/entities.json",
        "// Copyright © WHATWG (Apple, Google, Mozilla, Microsoft); BSD-3-Clause.",
        "// License and attribution: entity-data/LICENSE-WHATWG and entity-data/README.md.",
        "// SHA-256: " + hashlib.sha256(raw).hexdigest(),
        f"pub(super) const MAX_NAME_BYTES: usize = {max(len(n) for n, _ in names)};",
        "pub(super) static NAMES: &[(&str, &str)] = &[",
    ]
    lines.extend(f'    ("{name}", "{value}"),' for name, value in names)
    lines.extend([
        "];",
        "",
    ])
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--output-dir", type=Path, default=OUTPUT.parent)
    args = parser.parse_args()
    output = args.output_dir / OUTPUT.name
    content = generated()
    if args.check:
        if output.read_text() != content:
            raise SystemExit("character-reference table is stale")
    else:
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(content)
